#!/usr/bin/env python3
"""Rebuild static Unicode-range subsets without installing system fonts."""
from pathlib import Path
from collections import Counter
import hashlib
import json
import shutil
import sys
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
COMMIT = 'e9678a5385322c63730122ba464765baad83cfd8'
SOURCE_SHA256 = 'a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da'
BASE = f'https://raw.githubusercontent.com/google/fonts/{COMMIT}/ofl/notosanssc'
CACHE = ROOT / '.dev-tools/font-source'
OUTPUT = ROOT / 'assets/fonts'

try:
    from fontTools import subset
    from fontTools.ttLib import TTFont
    import brotli  # required for WOFF2 compression
except ImportError:
    sys.exit('Optional font rebuild needs fonttools and brotli. See docs/MAINTENANCE.md; preview needs neither.')

CACHE.mkdir(parents=True, exist_ok=True)
OUTPUT.mkdir(parents=True, exist_ok=True)
source = CACHE / 'NotoSansSC[wght].ttf'
if not source.exists():
    urllib.request.urlretrieve(f'{BASE}/NotoSansSC%5Bwght%5D.ttf', source)
if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
    sys.exit('Font source checksum mismatch; remove the cached source and retry.')
license_file = CACHE / 'OFL.txt'
if not license_file.exists():
    urllib.request.urlretrieve(f'{BASE}/OFL.txt', license_file)

# Retain GB2312 for ordinary future Chinese edits, plus every supported character
# in the current site, including its single-copy Chinese blog bodies.
unicodes = set(range(0x20, 0x2B0)) | set(range(0x2000, 0x2070)) | set(range(0xFF00, 0xFFF0))
for lead in range(0xA1, 0xF8):
    for trail in range(0xA1, 0xFF):
        try:
            unicodes.update(map(ord, bytes([lead, trail]).decode('gb2312')))
        except UnicodeDecodeError:
            pass
frequencies = Counter()
for directory in ['_pages', '_projects', '_posts', '_data', '_bibliography', '_includes/blog-content']:
    for path in (ROOT / directory).rglob('*'):
        if path.suffix in ['.md', '.yml', '.bib']:
            text = path.read_text(encoding='utf-8')
            unicodes.update(map(ord, text))
            frequencies.update(map(ord, text))

with TTFont(source, recalcTimestamp=False) as original:
    supported = set(original.getBestCmap())
unicodes &= supported

latin = {cp for cp in unicodes if 0x20 <= cp < 0x2B0 or 0x2000 <= cp < 0x2070}
common_text = (ROOT / '_pages/about-zh.md').read_text(encoding='utf-8')
common_text += (ROOT / '_data/i18n/zh-CN.yml').read_text(encoding='utf-8')
common_text += (ROOT / '_pages/awards-zh.md').read_text(encoding='utf-8')
for path in sorted((ROOT / '_projects').glob('*.zh.md')):
    common_text += path.read_text(encoding='utf-8').split('---', 2)[1]
common = (set(map(ord, common_text)) & unicodes) - latin
remaining = unicodes - latin - common
used = sorted(remaining & frequencies.keys(), key=lambda cp: (-frequencies[cp], cp))
reserve = sorted(remaining - frequencies.keys())
groups = [('latin', latin), ('common', common)]
groups += [(f'text-{index // 256 + 1:02}', set(used[index:index + 256])) for index in range(0, len(used), 256)]
groups += [(f'reserve-{index // 256 + 1:02}', set(reserve[index:index + 256])) for index in range(0, len(reserve), 256)]


def unicode_ranges(codepoints):
    """Compact, nonoverlapping CSS ranges; no fetch for unused characters."""
    values = sorted(codepoints)
    ranges = []
    start = last = values[0]
    for cp in values[1:]:
        if cp == last + 1:
            last = cp
            continue
        ranges.append(f'U+{start:X}' + (f'-{last:X}' if start != last else ''))
        start = last = cp
    ranges.append(f'U+{start:X}' + (f'-{last:X}' if start != last else ''))
    return ranges


manifest = {'family': 'Academic Sans', 'characters': len(unicodes), 'files': []}
css = ['/* Generated by bin/build-site-font.py; commit with its WOFF2 files. */']
emitted = set()
for label, codepoints in groups:
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.layout_features = ['*']
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    # Preserve copyright/license and the 100–900 variable axis. The upstream
    # reserved font name is "Source"; every subset shares our existing family.
    names = {1: 'Academic Sans', 2: 'Regular', 3: 'Academic Sans Subset 1.0',
             4: 'Academic Sans', 6: 'AcademicSans', 16: 'Academic Sans',
             17: 'Regular', 25: 'AcademicSans'}
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    font.flavor = 'woff2'
    temporary = CACHE / f'academic-sans-{label}.woff2'
    font.save(temporary)
    digest = hashlib.sha256(temporary.read_bytes()).hexdigest()
    filename = f'academic-sans-{label}-{digest[:12]}.woff2'
    shutil.copyfile(temporary, OUTPUT / filename)
    emitted.add(filename)
    manifest['files'].append({'file': filename, 'characters': len(codepoints), 'bytes': temporary.stat().st_size})
    if label in ['latin', 'common']:
        manifest[label] = f'/assets/fonts/{filename}'
    # A reserve may declare its interval, excluding all characters already used.
    # Its effective cmap still comes from the subset. This keeps declarations
    # compact without downloading reserves for existing content.
    declared = codepoints if not label.startswith('reserve-') else set(range(min(codepoints), max(codepoints) + 1)) - latin - common - set(used)
    css.append('\n'.join([
        '@font-face {', '  font-family: "Academic Sans";',
        f'  src: url("{filename}") format("woff2");',
        '  font-style: normal;', '  font-weight: 100 900;', '  font-display: swap;',
        '  unicode-range: ' + ', '.join(unicode_ranges(declared)) + ';', '}',
    ]))
    print(f'{filename}: {temporary.stat().st_size / 1024:.0f} KiB; {len(codepoints)} characters.', flush=True)
    font.close()

(OUTPUT / 'academic-sans.css').write_text('\n\n'.join(css) + '\n')
(ROOT / '_data/fonts.json').write_text(json.dumps(manifest, indent=2) + '\n')
# Keep the license wording intact and normalize upstream trailing whitespace.
(OUTPUT / 'OFL-NotoSansSC.txt').write_text('\n'.join(line.rstrip() for line in license_file.read_text(encoding='utf-8').splitlines()) + '\n', encoding='utf-8')
# Only remove outputs owned by this generator, after every replacement exists.
for path in OUTPUT.glob('academic-sans-*.woff2'):
    if path.name not in emitted:
        path.unlink()
legacy = OUTPUT / 'AcademicSans.woff2'
if legacy.exists():
    legacy.unlink()
print(f'Built {len(groups)} static subsets; {len(unicodes)} supported characters.')
